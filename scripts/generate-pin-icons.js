const SOURCE_DIR = path.resolve("components/icons/source/pin-info");
const OUTPUT_FILE = path.resolve("components/icons/PinIcons.tsx");

function walkDir(dir) {
  let results = [];
  try {
    const list = fs.readdirSync(dir);
    list.forEach(function (file) {
      if (file.startsWith(".")) return; // Skip hidden files
      const fullPath = path.join(dir, file);
      const stat = fs.statSync(fullPath);
      if (stat && stat.isDirectory()) {
        results = results.concat(walkDir(fullPath));
      } else if (file.endsWith(".svg")) {
        results.push(fullPath);
      }
    });
  } catch (e) {
    console.warn(`Warning: Could not read directory ${dir}`);
  }
  return results;
}

function generate() {
  console.log(`Scanning ${SOURCE_DIR}...`);
  const files = walkDir(SOURCE_DIR);
  console.log(`Found ${files.length} SVG files.`);

  let content = `// Auto-generated by scripts/generate-pin-icons.js
import React from "react";
import { IconWrapper, IconProps } from "./IconWrapper";

`;

  let count = 0;
  for (const fullPath of files) {
    // Get relative path from SOURCE_DIR to match mapping keys
    // e.g. /abs/path/to/infrastructure/1-1.svg -> infrastructure/1-1.svg
    const relativePath = path.relative(SOURCE_DIR, fullPath);

    // Normalize path separators for Windows compatibility if needed, though we seem to be on Mac
    const key = relativePath.split(path.sep).join("/");

    if (!iconMapping[key]) {
      console.warn(`Skipping unmapped file: ${key}`);
      continue;
    }

    const componentName = iconMapping[key];
    let svgContent = fs.readFileSync(fullPath, "utf8");

    // Remove <svg ...> tag and </svg>
    // Simple regex to extract inner content. Might be fragile if SVG has comments outside root.
    const match = svgContent.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
    if (!match) {
      console.warn(`Could not parse SVG content in ${key}`);
      continue;
    }
    svgContent = match[1];

    // Convert attributes to React format
    svgContent = svgContent
      .replace(/stroke-width/g, "strokeWidth")
      .replace(/stroke-linecap/g, "strokeLinecap")
      .replace(/stroke-linejoin/g, "strokeLinejoin")
      .replace(/fill-rule/g, "fillRule")
      .replace(/clip-rule/g, "clipRule")
      .replace(/clip-path/g, "clipPath")
      .replace(/fill-opacity/g, "fillOpacity")
      .replace(/stop-color/g, "stopColor")
      .replace(/stop-opacity/g, "stopOpacity")
      .replace(/class=/g, "className=")
      // Remove xml:space if present
      .replace(/xml:space="preserve"/g, "");

    content += `export function ${componentName}(props: IconProps) {
  return (
    <IconWrapper {...props}>
      ${svgContent.trim()}
    </IconWrapper>
  );
}\n\n`;
    count++;
  }

  fs.writeFileSync(OUTPUT_FILE, content);
  console.log(`Generated ${OUTPUT_FILE} with ${count} icons.`);
}

generate();
